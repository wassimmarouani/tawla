import { COLOR_TOKENS, PALETTE, THEME_EXTRAS, THEME_TOKENS, type ThemeName } from './tokens';

const INDENT = '  ';

function declarations(theme: ThemeName, depth: number): string {
  const pad = INDENT.repeat(depth);
  const colors = COLOR_TOKENS.map((token) => `${pad}--${token}: ${PALETTE[theme][token]};`);
  const extras = Object.entries(THEME_EXTRAS[theme]).map(
    ([name, value]) => `${pad}${name}: ${value};`,
  );
  return [`${pad}color-scheme: ${theme};`, ...colors, ...extras].join('\n');
}

/** Renders the full tokens.css (pure, so tests can compare it with the file on disk). */
export function renderTokensCss(): string {
  const themeMapping = COLOR_TOKENS.map((token) => `  --color-${token}: var(--${token});`);
  const aliases = [
    '  --color-primary: var(--brand-solid);',
    '  --color-primary-foreground: var(--brand-on-solid);',
    '  --color-ring: var(--brand-text);',
    '  --color-brand: var(--brand-solid);',
    '  --color-on-brand: var(--brand-on-solid);',
    '  --color-sidebar: var(--card);',
    '  --color-sidebar-foreground: var(--card-foreground);',
    '  --color-sidebar-primary: var(--brand-solid);',
    '  --color-sidebar-primary-foreground: var(--brand-on-solid);',
    '  --color-sidebar-accent: var(--accent);',
    '  --color-sidebar-accent-foreground: var(--accent-foreground);',
    '  --color-sidebar-border: var(--border);',
    '  --color-sidebar-ring: var(--brand-text);',
  ];
  const themeTokens = Object.entries(THEME_TOKENS).map(([name, value]) => `  ${name}: ${value};`);

  return `/*
 * GENERATED by \`pnpm tokens:build\` from src/styles/tokens.ts — do not edit by hand.
 * Design tokens "Tawla" (ADR-0029). The only stylesheet allowed to hold raw values.
 */

/* Dark variant: explicit [data-theme='dark'], or system dark when no theme is forced. */
@custom-variant dark {
  &:where([data-theme='dark'], [data-theme='dark'] *) {
    @slot;
  }
  @media (prefers-color-scheme: dark) {
    &:where(:root:not([data-theme='light']), :root:not([data-theme='light']) *) {
      @slot;
    }
  }
}

:root,
[data-theme='light'] {
${declarations('light', 1)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${declarations('dark', 2)}
  }
}

[data-theme='dark'] {
${declarations('dark', 1)}
}

@theme inline {
${[...themeMapping, ...aliases, ...themeTokens].join('\n')}
}
`;
}
