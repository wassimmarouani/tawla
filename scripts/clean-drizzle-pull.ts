/**
 * Post-processes `drizzle-kit pull` output (ADR-0003):
 * - removes the baseline SQL migration and meta/ snapshot it writes (SQL migrations live in
 *   supabase/migrations only);
 * - fixes known introspection quirks deterministically (auth.users references, SQL function
 *   defaults, unused callback parameters);
 * - formats the files so the CI drift check compares stable output.
 */
import { spawnSync } from 'node:child_process';
import { readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';

const OUT = path.resolve('src/lib/db/schema');
const HEADER =
  '// Generated by `pnpm db:pull` from the database (source of truth: supabase/migrations).\n' +
  '// Do not edit by hand.\n';
const AUTH_USERS =
  "import { authUsers as users } from 'drizzle-orm/supabase';\n\n" +
  '// relations.ts refers to auth.users under this name.\n' +
  'export { users as usersInAuth };\n';

function fixSchema(source: string): string {
  const fixed = source
    // SQL function defaults are emitted as bare TS calls, e.g. default(random_token()).
    .replace(/\.default\(([a-z_][a-z0-9_]*)\(\)\)/g, '.default(sql`$1()`)')
    // Table extras that never read `table` trip noUnusedParameters.
    .replace(/\(table\) => \[([\s\S]*?)\n\]\)/g, (block: string, body: string) =>
      body.includes('table.') ? block : block.replace('(table) => [', '() => ['),
    );
  // Foreign keys to auth.users reference `users`, which introspecting `public` cannot declare.
  return /\busers\.id\b/.test(fixed) && !fixed.includes('authUsers as users')
    ? AUTH_USERS + fixed
    : fixed;
}

for (const entry of await readdir(OUT, { withFileTypes: true })) {
  if (entry.isDirectory() || entry.name.endsWith('.sql')) {
    await rm(path.join(OUT, entry.name), { recursive: true, force: true });
  }
}

for (const file of ['schema.ts', 'relations.ts']) {
  const target = path.join(OUT, file);
  const source = (await readFile(target, 'utf8')).replace(HEADER, '');
  await writeFile(target, HEADER + (file === 'schema.ts' ? fixSchema(source) : source));
}

const prettier = path.resolve('node_modules/prettier/bin/prettier.cjs');
const result = spawnSync(process.execPath, [prettier, '--write', OUT], { stdio: 'inherit' });
process.exitCode = result.status ?? 1;
